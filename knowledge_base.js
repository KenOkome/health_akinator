// 判定補助：自由入力から主訴カテゴリを推定
function detectCategoryFromText(text) {
    if (!text) return "headache";
    const t = text.toLowerCase();
    if (t.includes("頭") || t.includes("こめかみ") || t.includes("ヘッド")) return "headache";
    if (t.includes("胃") || t.includes("腹") || t.includes("おなか") || t.includes("下痢") || t.includes("便秘") || t.includes("吐き気") || t.includes("胸焼け")) return "stomach";
    if (t.includes("熱") || t.includes("喉") || t.includes("のど") || t.includes("咳") || t.includes("鼻") || t.includes("風邪") || t.includes("インフル")) return "cold";
    if (t.includes("だる") || t.includes("疲れ") || t.includes("疲労") || t.includes("倦怠") || t.includes("重い") || t.includes("やる気")) return "fatigue";
    return "headache"; // デフォルト
}
